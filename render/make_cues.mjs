// Turns out/audio/cues.json into src/cues.js, so the picture knows the sung vowel and loudness of every frame.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cues = JSON.parse(await readFile(path.join(ROOT, 'out/audio/cues.json'), 'utf8'));
const { vowel, vocal_loudness: loud } = cues.per_frame;
if (vowel.length !== 1536 || loud.length !== 1536) throw new Error(`expected 1536 frames, got ${vowel.length} and ${loud.length}`);
const phrases = cues.events.filter(e => e.type === 'vocal_phrase' && e.edge === 'start' && e.singer === 'shio').map(e => [e.start_frame, e.end_frame]);
await writeFile(path.join(ROOT, 'src/cues.js'), `// Generated by render/make_cues.mjs from the soundtrack. Do not edit.
export const VOWEL = '${vowel.join('')}';
export const VOICE = [${loud.map(v => Math.round(v * 100) / 100).join(',')}];
export const PHRASES = ${JSON.stringify(phrases)};
`);
console.log(`cues: ${phrases.length} sung phrases`);
